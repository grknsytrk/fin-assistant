"""Modularized fund API service helpers.

Each submodule resolves patchable seams and shared mutable state at call time
via ``_fas()`` so ``app.fund_api_service`` remains the single owner for caches,
locks, TTLs, and test monkeypatches.
"""

from __future__ import annotations

import sys
from typing import Any


def _fas() -> Any:
    module = sys.modules.get("app.fund_api_service")
    if module is None:
        import app.fund_api_service as module
    return module


